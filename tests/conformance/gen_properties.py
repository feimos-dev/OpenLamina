#!/usr/bin/env python3
"""Generates the table of every tracked device property an OpenVR header names, with the type its name ends in, for
the property-sweep case.

  gen_properties.py <header> <output .cpp>

Each row is { value, name, type tag, array }: the type tag is OpenVR's PropertyTypeTag_t of the getter the case calls
(k_unStringPropertyTag for a string, ...), or of an array's elements. Markers (Prop_Invalid, *_Start, *_End, *_Max),
Prop_Reserved_*, binary properties and aliases of another name are left out; a name without a type ending gets the type
OpenVR gives it (Prop_ParentContainer, Prop_Hmd_AllowsClientToControlTextureIndex).
"""

import re
import sys
from pathlib import Path

# Name ending -> (type tag, array): the plain types have getters of their own; the rest are arrays of a type
SUFFIXES = [
    ("_Float_Array", "k_unFloatPropertyTag", True),
    ("_Int32_Array", "k_unInt32PropertyTag", True),
    ("_Vector4_Array", "k_unHmdVector4PropertyTag", True),
    ("_Matrix34_Array", "k_unHmdMatrix34PropertyTag", True),
    ("_Vector3", "k_unHmdVector3PropertyTag", True),
    ("_String", "k_unStringPropertyTag", False),
    ("_Bool", "k_unBoolPropertyTag", False),
    ("_Float", "k_unFloatPropertyTag", False),
    ("_Int32", "k_unInt32PropertyTag", False),
    ("_Uint64", "k_unUint64PropertyTag", False),
    ("_Matrix34", "k_unHmdMatrix34PropertyTag", False),
]
# Named without a type ending
UNSUFFIXED = {
    "Prop_ParentContainer": ("k_unUint64PropertyTag", False),
    "Prop_Hmd_AllowsClientToControlTextureIndex": ("k_unBoolPropertyTag", False),
}
SKIP = re.compile(r"^Prop_(Invalid|Reserved_\d+|.*_Start|.*_End|TrackedDeviceProperty_Max)$|_Binary$")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    text = Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace")
    m = re.search(r"enum\s+ETrackedDeviceProperty\s*\{(.*?)\}\s*;", text, re.S)
    if not m:
        sys.exit("gen_properties.py: no ETrackedDeviceProperty in the header")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    rows, seen = [], set()
    for name, value in re.findall(r"(Prop_\w+)\s*=\s*(\d+)", body):
        if SKIP.search(name) or name in seen:
            continue
        seen.add(name)
        typed = UNSUFFIXED.get(name)
        if not typed:
            typed = next(((tag, n) for suffix, tag, n in SUFFIXES if name.endswith(suffix)), None)
        if not typed:
            sys.exit(f"gen_properties.py: no type for {name}")
        rows.append((int(value), name, typed[0], typed[1]))
    rows.sort()
    out = ["// Generated by tests/conformance/gen_properties.py from " + Path(sys.argv[1]).name + ": don't edit",
           '#include "properties.h"', "", "const std::vector<PropertyRow>& AllProperties()", "{",
           "\tstatic const std::vector<PropertyRow> rows = {"]
    out += [f'\t\t{{ {v}, "{n[len("Prop_"):]}", vr::{tag}, {"true" if array else "false"} }},' for v, n, tag, array in rows]
    out += ["\t};", "\treturn rows;", "}", ""]
    Path(sys.argv[2]).parent.mkdir(parents=True, exist_ok=True)
    Path(sys.argv[2]).write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
